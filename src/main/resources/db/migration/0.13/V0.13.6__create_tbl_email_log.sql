CREATE SEQUENCE IF NOT EXISTS TRIALS.SEQ_EMAIL_LOG_ID START WITH 1 INCREMENT BY 1;


CREATE TABLE IF NOT EXISTS TRIALS.TBL_EMAIL_LOG (
    PN_ID INT NOT NULL PRIMARY KEY,

    -- Proveedor
    S_PROVIDER VARCHAR(30) NOT NULL,                 -- ejemplo: 'SENDPULSE'
    S_PROVIDER_MESSAGE_ID VARCHAR(80) NOT NULL,      -- id real de SendPulse (string)

    -- Contenido básico (útil para auditoría / reintentos / debug)
    S_TO_EMAIL VARCHAR(80) NOT NULL,
    S_TO_NAME VARCHAR(80),
    S_SUBJECT VARCHAR(200) NOT NULL,

    -- Estado interno (enum controlado por tu sistema)
    S_ESTADO VARCHAR(80) NOT NULL, -- 0=PENDIENTE_ENVIO, 1=ENVIADO, 2=LEIDO, 3=NO_ENTREGADO, 4=ERROR_ENVIO

    -- Respuesta SMTP / diagnóstico
    N_SMTP_ANSWER_CODE INTEGER,
    S_SMTP_ANSWER_SUBCODE VARCHAR(50),
    S_SMTP_ANSWER_DATA VARCHAR(2000),
    N_INTENTOS_VERIFICACION INTEGER NOT NULL DEFAULT 0,

    -- Fechas de eventos (si se pueden inferir/obtener)
    T_FECHA_ENVIO TIMESTAMP,
    T_FECHA_ENTREGA TIMESTAMP,
    T_FECHA_LECTURA TIMESTAMP,
    T_ULTIMA_VERIFICACION TIMESTAMP,
    T_PROXIMA_VERIFICACION TIMESTAMP,
);