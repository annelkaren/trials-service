(
    PN_ID       INT             NOT NULL PRIMARY KEY,
    S_NOMBRE    VARCHAR(250)    NOT NULL,
    S_ROL       VARCHAR(250)    NOT NULL,
    S_LINK      VARCHAR(250)    NOT NULL,
    N_ORDER     VARCHAR(250)    NOT NULL,
