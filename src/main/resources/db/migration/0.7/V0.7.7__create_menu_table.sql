    FOREIGN KEY (FN_PARENT) REFERENCES TRIALS.TBL_MENUS (PN_ID) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE INDEX IDX_MENUS1 ON TRIALS.TBL_MENUS (FN_PARENT);

